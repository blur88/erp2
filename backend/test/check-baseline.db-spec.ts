import { spawnSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { Client } from "pg";

const detector = resolve("dist/database/check-baseline.js");
const migrations = `CREATE TABLE migrations (
  id SERIAL PRIMARY KEY, timestamp bigint NOT NULL, name varchar NOT NULL)`;

// Neither DB_DATABASE nor DATABASE_URL selects a test target. Only names
// generated here and successfully created by this run enter the owned set.
const owned = new Set<string>();
const newName = () => `baseline_it_${randomUUID().replaceAll("-", "")}`;
function assertName(name: string): void {
  if (!/^baseline_it_[a-f0-9]{32}$/.test(name)) {
    throw new Error("Refusing a database name not generated by this suite");
  }
}

function connection(database: string): Client {
  return new Client({
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT),
    user: process.env.DB_USERNAME,
    password: process.env.DB_PASSWORD,
    database,
    ssl: false,
    connectionTimeoutMillis: 5000,
  });
}

// Include definitions (including indexes/constraints/defaults), sequence state,
// and every fixture row, rather than checking only the detector's table count.
async function snapshot(client: Client): Promise<unknown> {
  const catalogs = await client.query(`
    SELECT c.relname, c.relkind, a.attname,
           format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
           pg_get_expr(d.adbin, d.adrelid) AS default_expr,
           pg_get_indexdef(i.indexrelid) AS index_def,
           pg_get_constraintdef(k.oid) AS constraint_def
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0
    LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
    LEFT JOIN pg_index i ON i.indexrelid = c.oid
    LEFT JOIN pg_constraint k ON k.conrelid = c.oid
    WHERE n.nspname = 'public'
    ORDER BY c.relname, a.attnum, k.oid`);
  const tables = await client.query(`SELECT tablename FROM pg_tables
    WHERE schemaname = 'public' ORDER BY tablename`);
  const rows = {};
  for (const { tablename } of tables.rows) {
    const quoted = '"' + tablename.replaceAll('"', '""') + '"';
    rows[tablename] = (
      await client.query(`SELECT * FROM public.${quoted} ORDER BY 1`)
    ).rows;
  }
  const sequences = await client.query(`SELECT * FROM pg_sequences
    WHERE schemaname = 'public' ORDER BY sequencename`);
  return { catalogs: catalogs.rows, rows, sequences: sequences.rows };
}

function runDetector(database: string) {
  assertName(database);
  const cwd = mkdtempSync(join(tmpdir(), "baseline-it-"));
  try {
    writeFileSync(
      join(cwd, ".env"),
      `DB_DATABASE=${newName()}\nDB_MAX_CONNECTIONS=0\n`,
    );
    // Whitelist env: no inherited dotenv preloads, database URLs or PG options.
    return spawnSync(process.execPath, [detector], {
      cwd,
      encoding: "utf8",
      timeout: 30000,
      env: {
        PATH: process.env.PATH,
        NODE_ENV: "development",
        DB_HOST: process.env.DB_HOST,
        DB_PORT: process.env.DB_PORT,
        DB_USERNAME: process.env.DB_USERNAME,
        DB_PASSWORD: process.env.DB_PASSWORD,
        DB_DATABASE: database,
        DB_SSL: "false",
        DB_SYNCHRONIZE: "true",
        DB_LOGGING: "false",
        DB_CONNECTION_TIMEOUT: "5000",
      },
    });
  } finally {
    rmSync(cwd, { recursive: true, force: true });
  }
}

beforeAll(() => {
  for (const key of ["DB_HOST", "DB_PORT", "DB_USERNAME", "DB_PASSWORD"]) {
    if (!process.env[key]) throw new Error(`test:db requires non-empty ${key}`);
  }
  const port = Number(process.env.DB_PORT);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error("test:db requires a valid DB_PORT");
  }
});

const cases = [
  ["empty database", [], "FRESH"],
  [
    "user table without migration history",
    [
      "CREATE TABLE probe (id integer PRIMARY KEY)",
      "INSERT INTO probe VALUES (42)",
    ],
    "UNTRACKED_SCHEMA",
  ],
  [
    "user table with empty migration history",
    ["CREATE TABLE probe (id integer PRIMARY KEY)", migrations],
    "UNTRACKED_SCHEMA",
  ],
  [
    "recorded migration",
    [
      "CREATE TABLE probe (id integer PRIMARY KEY)",
      migrations,
      "INSERT INTO migrations (timestamp, name) VALUES (1234567890000, 'Fixture1234567890000')",
    ],
    "BASELINED",
  ],
  ["only empty migration table", [migrations], "FRESH"],
] as const;

test.each(cases)(
  "%s: emits the expected token without writes",
  async (_label, setup, expected) => {
    const database = newName();
    assertName(database);
    const admin = connection("postgres");
    const client = connection(database);
    try {
      await admin.connect();
      await admin.query(`CREATE DATABASE "${database}" TEMPLATE template0`);
      owned.add(database);
      await client.connect();
      for (const sql of setup) await client.query(sql);
      const before = await snapshot(client);
      const result = runDetector(database);
      expect(result.error).toBeUndefined();
      expect(result.signal).toBeNull();
      expect(result.status).toBe(0);
      expect(result.stderr).toBe("");
      expect(result.stdout).toBe(expected);
      expect(await snapshot(client)).toEqual(before);
    } finally {
      try {
        await client.end();
      } finally {
        try {
          if (owned.has(database)) {
            assertName(database);
            await admin.query(`DROP DATABASE "${database}" WITH (FORCE)`);
            owned.delete(database);
          }
        } finally {
          await admin.end();
        }
      }
    }
  },
);

test("never-created database fails with empty stdout", () => {
  const result = runDetector(newName());
  expect(result.error).toBeUndefined();
  expect(result.signal).toBeNull();
  expect(result.status).toBe(1);
  expect(result.stdout).toBe("");
  expect(result.stderr).toContain(
    "[check-baseline] Failed to determine migration baseline state.",
  );
});
