// Cover the AI attribution detector shared by the Breaking Change Check and the commit-msg hook (#2017).
const assert = require('node:assert/strict');
const { test } = require('node:test');
const { findAttribution, attributionFailures } = require('../ai-attribution.cjs');

const reasons = (text, options) => findAttribution(text, options).map(({ line, reason }) => `${line}:${reason}`);

test('rejects an AI Co-Authored-By trailer in every common spelling', () => {
  for (const trailer of [
    'Co-Authored-By: Claude <noreply@anthropic.com>',
    'Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>',
    'Co-Authored-By: Claude Opus 4.1 <noreply@anthropic.com>',
    'Co-Authored-By: Claude Code <noreply@anthropic.com>',
    'co-authored-by: claude <noreply@anthropic.com>',
    'CO-AUTHORED-BY: CLAUDE <NOREPLY@ANTHROPIC.COM>',
    'Co-authored-by: ChatGPT <noreply@openai.com>',
    'Co-authored-by: GPT-5 <noreply@openai.com>',
    'Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>',
    'Co-authored-by: Gemini <gemini@example.test>',
    'Co-authored-by: Gemini 3 Pro <noreply@google.com>',
    'Co-authored-by: OpenAI Codex <codex@example.test>',
    'Co-authored-by: Cursor Agent <cursoragent@cursor.com>',
    'Co-authored-by: Devin AI <devin-ai-integration[bot]@users.noreply.github.com>',
    'Co-authored-by: Aider <noreply@aider.chat>',
    'Co-Authored-By: Someone <anyone@anthropic.com>',
    'Co-Authored-By: "Claude" <noreply@anthropic.com>',
    'Co-Authored-By:Claude <noreply@anthropic.com>',
    'Co-Authored-By :  Claude <noreply@anthropic.com>',
    'Co-Authored-By: Claude',
    'Co-Authored-By: Claude <>',
    'Co-Authored-By: noreply@anthropic.com',
    'Co-Authored-By: Cl​aude <noreply@anthropic.com>',
    '  Co-Authored-By: Claude <noreply@anthropic.com>   ',
    '> Co-Authored-By: Claude <noreply@anthropic.com>',
    '- Co-Authored-By: Claude <noreply@anthropic.com>',
    'Co-Authored-By: Claude <noreply@anthropic.com>\r',
  ]) {
    assert.equal(findAttribution(`fix: example\n\n${trailer}`).length, 1, trailer);
  }
});

test('rejects equivalent attribution trailers that name an AI assistant', () => {
  for (const key of ['Authored-By', 'Co-Developed-By', 'Assisted-By', 'Generated-By', 'Created-By',
    'Written-By', 'Signed-off-by', 'Reviewed-by', 'Co_Authored_By']) {
    assert.equal(findAttribution(`${key}: Claude <noreply@anthropic.com>`).length, 1, key);
  }
});

test('rejects Claude-Session lines whatever they contain', () => {
  for (const line of ['Claude-Session: session_01AbC', 'claude-session: x', 'Claude-Session:', 'Claude-Session-Id: 42',
    'Claude-Session: https://example.test/not-a-claude-url']) {
    assert.deepEqual(reasons(line), ['1:Claude-Session line'], line);
  }
});

test('rejects recognized AI session URLs, bare or wrapped', () => {
  for (const line of [
    'https://claude.ai/code/session_01AbCdEf',
    'Session: https://claude.ai/code/session_01AbCdEf',
    '[session](https://claude.ai/code/session_01AbCdEf)',
    '<https://claude.ai/code/session_01AbCdEf>',
    'https://claude.ai/share/0a1b2c3d',
    'https://claude.ai/chat/0a1b2c3d-4e5f',
    'https://chatgpt.com/share/68a1b2c3',
    'https://chatgpt.com/c/68a1b2c3',
    'https://chat.openai.com/share/68a1b2c3',
    'https://gemini.google.com/app/0a1b2c3d',
    'HTTPS://CLAUDE.AI/CODE/SESSION_01ABC',
  ]) {
    assert.deepEqual(reasons(line), ['1:AI session URL'], line);
  }
});

test('rejects generated-with and generated-by attribution lines', () => {
  for (const line of [
    '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    'Generated with Claude Code',
    '🤖 Generated with Claude Code 🤖',
    'Generated by ChatGPT',
    'generated by GitHub Copilot',
    'Created with Cursor',
    '*Written with Gemini*',
    '> Authored by Claude',
    'Assisted by OpenAI Codex',
    'Generated with AI assistance',
    'Co-authored with Claude',
  ]) {
    assert.deepEqual(reasons(line), ['1:AI attribution line'], line);
  }
});

test('reports each violation with its line number', () => {
  const message = [
    'fix: example', '', 'Body mentions Claude Code in passing.', '',
    'Co-Authored-By: Claude <noreply@anthropic.com>', 'Claude-Session: abc',
  ].join('\n');
  assert.deepEqual(reasons(message), ['5:AI co-author trailer', '6:Claude-Session line']);
  assert.equal(findAttribution(message)[0].text, 'Co-Authored-By: Claude <noreply@anthropic.com>');
});

test('accepts human co-author trailers, including a human named Claude', () => {
  for (const trailer of [
    'Co-Authored-By: Jane Doe <jane@example.test>',
    'Co-authored-by: Claude Dupont <claude@example.test>',
    'Co-authored-by: Claudette Gemini-Rossi <claudette@example.test>',
    'Co-authored-by: Devin Patel <devin@example.test>',
    'Co-authored-by: Cursor Smith <cursor.smith@example.test>',
    'Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>',
    'Co-Authored-By: Jane Doe',
    'Signed-off-by: Jane Doe <jane@example.test>',
    'Reviewed-by: Claude Dupont <claude@example.test>',
  ]) {
    assert.deepEqual(findAttribution(`fix: example\n\n${trailer}`), [], trailer);
  }
});

test('accepts prose, code spans and links that merely mention AI tools or the rule', () => {
  for (const line of [
    'We use Claude Code for exploration but write every commit ourselves.',
    'See https://claude.ai/code for the product page.',
    'See https://docs.anthropic.com/en/docs/claude-code/hooks for hook documentation.',
    'https://chatgpt.com/ is the front page, not a conversation.',
    'The `Co-Authored-By: Claude` trailer is rejected by the check.',
    'Reject `Claude-Session:` lines and session URLs.',
    'Generated with the OpenAPI generator.',
    'Generated by `npm run build`.',
    'This was written by hand with care.',
    'Copilot-style completions are out of scope.',
    'Fix the Claude Code review hook ordering.',
    'Heading: Co-Authored-By: Claude <noreply@anthropic.com>',
    '',
  ]) {
    assert.deepEqual(findAttribution(line), [], line);
  }
});

test('detects attribution inside code fences and HTML comments in a PR body', () => {
  const body = ['## Summary', '```text', 'Co-Authored-By: Claude <noreply@anthropic.com>', '```',
    '<!-- Claude-Session: hidden -->'].join('\n');
  assert.deepEqual(reasons(body), ['3:AI co-author trailer', '5:Claude-Session line']);
});

test('skips git comment lines and everything below the scissors line only when asked', () => {
  const message = [
    'fix: example', '', '# Co-Authored-By: Claude <noreply@anthropic.com>',
    'Co-Authored-By: Jane Doe <jane@example.test>',
    '# ------------------------ >8 ------------------------',
    'Co-Authored-By: Claude <noreply@anthropic.com>',
  ].join('\n');
  assert.deepEqual(findAttribution(message, { gitComments: true }), []);
  assert.deepEqual(reasons(message), ['3:AI co-author trailer', '6:AI co-author trailer']);
  assert.deepEqual(reasons('# Claude-Session: x', { gitComments: true }), []);
});

test('truncates a very long offending line in the report', () => {
  const [violation] = findAttribution(`Co-Authored-By: Claude <noreply@anthropic.com> ${'x'.repeat(500)}`);
  assert.ok(violation.text.length <= 120, violation.text.length);
});

test('detects an attribution trailer in a non-final commit', () => {
  const failures = attributionFailures({
    body: 'clean body',
    commits: [
      { hash: 'a'.repeat(40), message: 'feat: first\n\nCo-Authored-By: Claude <noreply@anthropic.com>' },
      { hash: 'b'.repeat(40), message: 'fix: second' },
    ],
  });
  assert.equal(failures.length, 1);
  assert.match(failures[0], /^commit aaaaaaaaaaaa line 3: AI co-author trailer: "Co-Authored-By: Claude/);
});

test('collects violations from every commit and the PR body', () => {
  const failures = attributionFailures({
    body: '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    commits: [
      { hash: 'a'.repeat(40), message: 'feat: first\n\nClaude-Session: x' },
      { hash: 'b'.repeat(40), message: 'fix: second\n\nCo-Authored-By: Jane Doe <jane@example.test>' },
      { hash: 'c'.repeat(40), message: 'fix: third\n\nCo-Authored-By: Claude <noreply@anthropic.com>' },
    ],
  });
  assert.equal(failures.length, 3);
  assert.match(failures[0], /^PR body line 1: AI attribution line/);
  assert.match(failures[1], /^commit aaaaaaaaaaaa line 3: Claude-Session line/);
  assert.match(failures[2], /^commit cccccccccccc line 3: AI co-author trailer/);
});

test('accepts a clean body and commit list', () => {
  assert.deepEqual(attributionFailures({
    body: '## Summary\n\nPlain text.',
    commits: [{ hash: 'a'.repeat(40), message: 'fix: example\n\nCo-Authored-By: Jane Doe <jane@example.test>' }],
  }), []);
});

test('fails closed on a missing body, a missing commit list or a malformed commit', () => {
  const commits = [{ hash: 'a'.repeat(40), message: 'fix: example' }];
  for (const body of [undefined, null, 42, {}]) {
    assert.throws(() => attributionFailures({ body, commits }), /PR body is missing or inaccessible/);
  }
  for (const list of [undefined, null, [], 'fix: example', {}]) {
    assert.throws(() => attributionFailures({ body: 'ok', commits: list }), /commit list is missing or empty/);
  }
  for (const commit of [null, {}, { hash: 'a'.repeat(40) }, { hash: 'a'.repeat(40), message: 7 }, { message: 'fix: x' }]) {
    assert.throws(() => attributionFailures({ body: 'ok', commits: [commit] }), /commit .*malformed|malformed commit/i);
  }
});

test('an empty PR body string is present, not missing', () => {
  assert.deepEqual(attributionFailures({ body: '', commits: [{ hash: 'a'.repeat(40), message: 'fix: x' }] }), []);
});
