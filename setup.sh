#!/bin/bash

# ERP System Production Setup Script
# Requirements: docker-compose.prod.yml + this file only

set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

print_status()  { echo -e "${BLUE}[INFO]${NC} $1"; }
print_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
print_warning() { echo -e "${YELLOW}[WARNING]${NC} $1"; }
print_error()   { echo -e "${RED}[ERROR]${NC} $1"; }

COMPOSE_FILE="docker-compose.prod.yml"

# Check prerequisites
check_prerequisites() {
    print_status "Checking prerequisites..."

    if ! command -v docker &> /dev/null; then
        print_error "Docker is not installed. Please install Docker first."
        exit 1
    fi

    if ! docker compose version &> /dev/null; then
        print_error "Docker Compose is not available. Please install Docker Compose."
        exit 1
    fi

    if [ ! -f "$COMPOSE_FILE" ]; then
        print_error "$COMPOSE_FILE not found in current directory."
        exit 1
    fi

    print_success "Prerequisites check passed"
}

# Generate a random secret
generate_secret() {
    node -e "console.log(require('crypto').randomBytes(64).toString('hex'))" 2>/dev/null \
        || openssl rand -hex 64 2>/dev/null \
        || cat /dev/urandom | tr -dc 'a-f0-9' | head -c 128
}

# Generate a random password
generate_password() {
    openssl rand -base64 16 2>/dev/null \
        || cat /dev/urandom | tr -dc 'A-Za-z0-9!@#$%' | head -c 16
}

# Setup .env file
setup_environment() {
    if [ -f .env ]; then
        print_warning ".env file already exists. Skipping environment setup."
        return
    fi

    print_status "Setting up environment configuration..."
    echo ""
    echo "Press ENTER to use the auto-generated value, or type your own."
    echo ""

    # Domain
    read -p "  Domain / server IP (e.g. https://erp.example.com): " INPUT_DOMAIN
    DOMAIN=${INPUT_DOMAIN:-http://localhost}

    # Database password
    DEFAULT_DB_PASS=$(generate_password)
    read -p "  Database password [auto: $DEFAULT_DB_PASS]: " INPUT_DB_PASS
    DB_PASS=${INPUT_DB_PASS:-$DEFAULT_DB_PASS}

    # Redis password
    DEFAULT_REDIS_PASS=$(generate_password)
    read -p "  Redis password [auto: $DEFAULT_REDIS_PASS]: " INPUT_REDIS_PASS
    REDIS_PASS=${INPUT_REDIS_PASS:-$DEFAULT_REDIS_PASS}

    # JWT secret
    DEFAULT_JWT_SECRET=$(generate_secret)
    read -p "  JWT secret [auto-generated, press ENTER]: " INPUT_JWT_SECRET
    JWT_SECRET=${INPUT_JWT_SECRET:-$DEFAULT_JWT_SECRET}

    echo ""

    cat > .env <<EOF
# Generated by setup.sh on $(date)

# Application
NODE_ENV=production

# Database
DATABASE_HOST=postgres
DATABASE_PORT=5432
DATABASE_NAME=erp_db
DATABASE_USERNAME=erp_user
DATABASE_PASSWORD=${DB_PASS}
DATABASE_LOGGING=false
DATABASE_SYNCHRONIZE=false
DATABASE_SSL=false

# Redis
REDIS_HOST=redis
REDIS_PORT=6379
REDIS_PASSWORD=${REDIS_PASS}
REDIS_DB=0
REDIS_TTL=3600

# JWT
JWT_SECRET=${JWT_SECRET}
JWT_EXPIRES_IN=15m
JWT_REFRESH_EXPIRES_IN=7d
JWT_AUDIENCE=erp-app
JWT_ISSUER=erp-backend

# Security
ALLOWED_ORIGINS=${DOMAIN}
FRONTEND_URL=${DOMAIN}
CSP_REPORT_ONLY=false
RATE_LIMIT_WINDOW_MS=900000
RATE_LIMIT_MAX=100
HSTS_MAX_AGE=31536000
HSTS_INCLUDE_SUBDOMAINS=true
HSTS_PRELOAD=true

# Logging
LOG_LEVEL=warn
LOG_FORMAT=combined
ENABLE_REQUEST_LOGGING=true
ENABLE_METRICS=false
ENABLE_SWAGGER=false
DEBUG_MODE=false
EOF

    print_success ".env file created"
}

# Create required directories
create_directories() {
    print_status "Creating required directories..."
    mkdir -p data/postgres data/redis uploads logs backups
    print_success "Directories created"
}

# Pull and start services
deploy_services() {
    print_status "Pulling images..."
    docker compose -f "$COMPOSE_FILE" pull

    print_status "Starting services..."
    docker compose -f "$COMPOSE_FILE" up -d
    print_success "Services started"
}

# BEGIN wait-ready.sh (verbatim copy of scripts/lib/wait-ready.sh; edit there)
# shellcheck shell=bash
# Bounded readiness waits for deploy.sh and setup.sh (#1959).
#
# setup.sh must run with only docker-compose.prod.yml beside it, so it embeds
# a verbatim copy of this file between its "BEGIN wait-ready.sh" and
# "END wait-ready.sh" markers; scripts/__tests__/wait-ready.test.js fails if
# the copy drifts. Edit this file, then paste it into setup.sh.
#
# Every wait has its own deadline of READY_TIMEOUT seconds (default 180). No
# single attempt may outlive the deadline, and a success that arrives after it
# is reported as a timeout. On timeout the caller's print_compose_status
# function, if defined, prints diagnostics.
#
# Safe under `set -e`: failures are returned, never raised.

ready_error() {
    if declare -F print_error >/dev/null; then
        print_error "$1"
    else
        echo "ERROR: $1" >&2
    fi
}

ready_timeout_report() {
    ready_error "$1"
    if declare -F print_compose_status >/dev/null; then
        print_compose_status || true
    fi
}

# Run a command, terminating it if it outlives the given number of seconds.
# Returns the command's status (non-zero if it was terminated).
ready_run_bounded() {
    local limit="$1" pid watcher status
    shift
    "$@" &
    pid=$!
    ( sleep "$limit"; kill -TERM "$pid" 2>/dev/null ) >/dev/null 2>&1 &
    watcher=$!
    status=0
    wait "$pid" || status=$?
    kill "$watcher" 2>/dev/null || true
    wait "$watcher" 2>/dev/null || true
    return "$status"
}

ready_sleep_until() {
    local deadline="$1" remaining
    remaining=$((deadline - SECONDS))
    if [ "$remaining" -gt 5 ]; then
        remaining=5
    fi
    if [ "$remaining" -gt 0 ]; then
        sleep "$remaining"
    fi
}

# wait_for_http_200 URL
wait_for_http_200() {
    local url="$1"
    local timeout="${READY_TIMEOUT:-180}"
    local deadline=$((SECONDS + timeout))
    local remaining code=none
    while :; do
        remaining=$((deadline - SECONDS))
        if [ "$remaining" -le 0 ]; then
            ready_timeout_report "No HTTP 200 from $url within ${timeout}s (last status: $code)"
            return 1
        fi
        code=$(curl -s -o /dev/null -w '%{http_code}' --max-time "$remaining" "$url" 2>/dev/null) || true
        code="${code:-000}"
        if [ "$code" = "200" ] && [ "$SECONDS" -lt "$deadline" ]; then
            return 0
        fi
        ready_sleep_until "$deadline"
    done
}

# wait_for_command DESCRIPTION COMMAND [ARGS...]
wait_for_command() {
    local description="$1"
    shift
    local timeout="${READY_TIMEOUT:-180}"
    local deadline=$((SECONDS + timeout))
    local remaining
    while :; do
        remaining=$((deadline - SECONDS))
        if [ "$remaining" -le 0 ]; then
            ready_timeout_report "$description not ready within ${timeout}s"
            return 1
        fi
        if ready_run_bounded "$remaining" "$@" && [ "$SECONDS" -lt "$deadline" ]; then
            return 0
        fi
        ready_sleep_until "$deadline"
    done
}
# END wait-ready.sh

# Diagnostics printed by the waits on timeout.
print_compose_status() {
    docker compose -f "$COMPOSE_FILE" ps
}


# Wait for the Ingress (port 80, the only published entry point) to reach the
# backend and serve the frontend.
wait_for_services() {
    print_status "Waiting for services to be ready..."

    print_status "Waiting for backend through the Ingress..."
    wait_for_http_200 http://localhost/api/health

    print_status "Waiting for frontend through the Ingress..."
    wait_for_http_200 http://localhost/

    print_success "All services are ready"
}

# Show status
show_status() {
    docker compose -f "$COMPOSE_FILE" ps

    echo ""
    print_success "ERP System deployed successfully!"
    echo ""
    echo "Access: ${DOMAIN:-http://localhost}"
    echo ""
    echo "Default credentials:"
    echo "  Username: admin"
    echo "  Password: Admin@123!"
    echo "  ** Change password immediately after first login! **"
    echo ""
    echo "Useful commands:"
    echo "  View logs:    docker compose -f $COMPOSE_FILE logs -f"
    echo "  Restart:      docker compose -f $COMPOSE_FILE restart"
    echo "  Stop:         docker compose -f $COMPOSE_FILE down"
    echo "  Status:       docker compose -f $COMPOSE_FILE ps"
    echo ""
}

cleanup_on_error() {
    print_error "Setup failed. Stopping services..."
    docker compose -f "$COMPOSE_FILE" down
    exit 1
}

trap cleanup_on_error ERR

# Main
echo "==============================================="
echo "   ERP System - Production Setup Script"
echo "==============================================="
echo ""

case "${1:-setup}" in
    "setup")
        check_prerequisites
        setup_environment
        create_directories
        deploy_services
        wait_for_services
        show_status
        ;;
    "start")
        docker compose -f "$COMPOSE_FILE" up -d
        ;;
    "stop")
        docker compose -f "$COMPOSE_FILE" down
        ;;
    "restart")
        docker compose -f "$COMPOSE_FILE" restart
        ;;
    "logs")
        docker compose -f "$COMPOSE_FILE" logs -f
        ;;
    "status")
        docker compose -f "$COMPOSE_FILE" ps
        ;;
    "update")
        print_status "Pulling latest images..."
        docker compose -f "$COMPOSE_FILE" pull
        docker compose -f "$COMPOSE_FILE" up -d
        print_success "Update complete"
        ;;
    *)
        echo "Usage: $0 {setup|start|stop|restart|logs|status|update}"
        echo ""
        echo "  setup   - First time setup: generate .env and deploy (default)"
        echo "  start   - Start services"
        echo "  stop    - Stop services"
        echo "  restart - Restart services"
        echo "  logs    - View real-time logs"
        echo "  status  - Show service status"
        echo "  update  - Pull latest images and redeploy"
        exit 1
        ;;
esac
